"""Generates the static paths (ticks, coloured arcs) of the round instruments in ui/.

On the RP2040 a static path must never be redrawn because a hand moves, so no box of a static
path may overlap the box of a hand at any hand angle. The ticks are therefore grouped, and the
arcs cut, into paths whose boxes stay outside the reach of the hands. The script checks this for
every hand angle in steps of 0.1 degree.

Every coordinate is written as `size_float * A + B` with precomputed A and B, so each binding
depends on a single property (B is only the margin of the viewboxes, widths scale with the size
like the widths of Theme): written with functions of `center`, `inner_radius` and so on,
the dependency nodes of the bindings cost about 16 KB more heap (measured with
tools/host-check).

Usage:
    python3 tools/dial-paths.py           # rewrite the generated paths in the .slint files
    python3 tools/dial-paths.py --check   # fail if a .slint file is not up to date

The generated part of a file lies between the BEGIN and END marker lines. Run the script again
after changing anything below, Theme.ring_ratio, Theme.marking_width or the hands.
"""

import math
import sys
from dataclasses import dataclass, field
from pathlib import Path

# the same values as in ui/theme.slint
RING_RATIO = 0.10  # Theme.ring_ratio
MARKING_WIDTH = 3.0  # Theme.marking_width in px at SIZE (Theme.reference_size)
VEHICLE_WIDTH = 3.0  # Theme.vehicle_width in px at SIZE

SIZE = 240  # Theme.reference_size, used for the checks, the output scales with the size
CENTER = SIZE / 2
INNER_RADIUS = SIZE * (0.5 - RING_RATIO)

BEGIN = "        // BEGIN generated by tools/dial-paths.py, do not edit"
END = "        // END generated by tools/dial-paths.py"

# counterclockwise on the screen, see counterclockwise()
TICK_CORNERS = [("inner", 1), ("outer", 1), ("outer", -1), ("inner", -1)]


@dataclass
class Tick:
    """a radial mark drawn as a thin filled quadrilateral"""

    angle: float  # degree, clockwise from 12 o'clock
    inner: float  # distances from the center, relative to the inner radius
    outer: float
    half_width: float  # px
    color: str


@dataclass
class Arc:
    """a coloured band along the dial"""

    start: float  # degree, clockwise from 12 o'clock
    end: float
    inner: float  # distances from the center, relative to the inner radius
    outer: float
    color: str
    name: str


@dataclass
class Hand:
    """a moving hand, the shape of the hands in the .slint files"""

    tip: float  # relative to the inner radius
    shoulder: float
    tail: float
    half_width: float  # px


@dataclass
class Card:
    """a card that turns as a whole (heading indicator): its paths are redrawn every frame"""

    ticks: list  # Tick at their angle on the card
    paths: int  # number of paths the ticks are split into (each rebuilds its elements per frame)
    labels: list  # (angle, text) on the card, the text stays upright
    label_radius: float  # relative to the inner radius


@dataclass
class Shape:
    """a static filled shape, polygons in units of the inner radius from the center (y down)"""

    name: str
    color: str
    polygons: list
    # drawn over the turning card on purpose (redrawn with it), not checked for overlap
    over_card: bool = False
    # an outline instead of a filled shape: the stroke width as a .slint expression and in px at
    # SIZE, for the checks
    stroke_width: str = None
    stroke_px: float = 0
    # an outline of open lines instead of closed polygons, with flat ends
    closed: bool = True


@dataclass
class Rotor:
    """a shape that turns around the center by up to +-max_angle (the wings or the tail of the
    aircraft symbol of the turn coordinator), polygons in units of the inner radius from the
    center (y down); one path with a box that follows it"""

    name: str
    color: str
    polygons: list
    max_angle: float  # degree
    sin_name: str  # properties with the sine and cosine of the angle in the .slint file
    cos_name: str


@dataclass
class Dial:
    file: str
    min_distance: float  # smallest distance of a static box from the center, rel. inner radius
    hands: list
    ticks: list = field(default_factory=list)
    arcs: list = field(default_factory=list)
    # ticks drawn after the normal ticks (for example a red line), each in its own path
    marks: list = field(default_factory=list)
    # groups of ticks chosen by hand instead of the grouping by distance
    groups: list = None
    card: Card = None
    shapes: list = field(default_factory=list)
    rotors: list = field(default_factory=list)
    # boxes of hand-written static elements (Rectangle, Text), in units of the inner radius
    # from the center (x0, y0, x1, y1), checked against the rotors
    statics: list = field(default_factory=list)
    # ring thickness relative to the size, Theme.ring_ratio unless the dial has no bezel ring
    ring_ratio: float = RING_RATIO
    # pixels (at SIZE) of static boxes a hand box may cover at any angle: that part of them is
    # redrawn with the hand. 0: moving hands never make a static part be redrawn.
    max_overlap: float = 0


# ring ratio of the dial being generated (Dial.ring_ratio), set by use_dial()
ring_ratio = RING_RATIO


def use_dial(dial):
    """sizes of the dial being generated: the inner radius follows its ring ratio"""
    global ring_ratio, INNER_RADIUS
    ring_ratio = dial.ring_ratio
    INNER_RADIUS = SIZE * (0.5 - ring_ratio)


def ratio(r):
    """distance relative to the inner radius -> relative to the instrument size"""
    return (0.5 - ring_ratio) * r


def tick_coefficients(tick, corner, axis):
    """A and B of the coordinate `size_float * A + B` of a tick corner"""
    along, side = corner
    a = math.radians(tick.angle)
    r = ratio(tick.outer if along == "outer" else tick.inner)
    # the width scales with the instrument like Theme.marking_width, so it is part of A: the
    # same coordinates at SIZE, and the same proportions at any other size
    half_width = tick.half_width * side / SIZE
    if axis == "x":
        return 0.5 + r * math.sin(a) + half_width * math.cos(a), 0
    return 0.5 - r * math.cos(a) + half_width * math.sin(a), 0


def arc_point(angle, r):
    """A of x and y of a point on an arc (B is 0)"""
    a = math.radians(angle)
    return 0.5 + ratio(r) * math.sin(a), 0.5 - ratio(r) * math.cos(a)


def tick_extremes(group):
    """(A, B) of the smallest and largest x and y of a group of ticks"""
    corners = [(t, c) for t in group for c in TICK_CORNERS]

    def value(e, axis):
        a, b = tick_coefficients(*e, axis)
        return a * SIZE + b

    x0 = min(corners, key=lambda e: value(e, "x"))
    x1 = max(corners, key=lambda e: value(e, "x"))
    y0 = min(corners, key=lambda e: value(e, "y"))
    y1 = max(corners, key=lambda e: value(e, "y"))
    return (
        tick_coefficients(*x0, "x"),
        tick_coefficients(*y0, "y"),
        tick_coefficients(*x1, "x"),
        tick_coefficients(*y1, "y"),
    )


def arc_extremes(arc, start, end):
    """(A, 0) of the smallest and largest x and y of a piece of an arc"""
    angles = [start, end] + [a for a in range(0, 721, 90) if start < a < end]
    points = [arc_point(a, r) for a in angles for r in (arc.inner, arc.outer)]
    xs = [p[0] for p in points]
    ys = [p[1] for p in points]
    return (min(xs), 0), (min(ys), 0), (max(xs), 0), (max(ys), 0)


def box(extremes):
    """box in px at SIZE, with the 1 unit margin of the viewbox"""
    (ax0, bx0), (ay0, by0), (ax1, bx1), (ay1, by1) = extremes
    return (
        ax0 * SIZE + bx0 - 1,
        ay0 * SIZE + by0 - 1,
        ax1 * SIZE + bx1 + 1,
        ay1 * SIZE + by1 + 1,
    )


def distance(b):
    """distance of the box from the center"""
    dx = max(b[0] - CENTER, 0, CENTER - b[2])
    dy = max(b[1] - CENTER, 0, CENTER - b[3])
    return math.hypot(dx, dy)


def group_ticks(ticks, min_distance):
    """fewest groups of neighbouring ticks whose boxes keep the distance"""
    best = None
    for start in range(len(ticks)):
        result, current = [], []
        for i in range(len(ticks)):
            index = (start + i) % len(ticks)
            candidate = [ticks[k] for k in current + [index]]
            if current and distance(box(tick_extremes(candidate))) < min_distance:
                result.append(current)
                current = [index]
            else:
                current.append(index)
        result.append(current)
        if best is None or len(result) < len(best):
            best = result
    return [[ticks[k] for k in g] for g in sorted(best, key=lambda g: g[0])]


def join_extremes(a, b):
    """extremes of the union of two boxes given as extremes"""

    def value(e):
        return e[0] * SIZE + e[1]

    return (
        min(a[0], b[0], key=value),
        min(a[1], b[1], key=value),
        max(a[2], b[2], key=value),
        max(a[3], b[3], key=value),
    )


def group_ticks_and_arcs(ticks, arcs, min_distance):
    """fewest groups of neighbouring ticks and pieces of arcs of their colour (the white arc of
    the airspeed indicator) whose boxes keep the distance, as (ticks, arc pieces)

    A path has one fill, so an arc of the ticks' colour can share their paths instead of having
    paths of its own: each Path element costs heap, and stack when the instrument is created.
    The arcs are cut into slices of 0.25 degree, grouped like ticks, and the slices of a group
    are joined into one piece per arc.
    """
    items = [(t.angle, tick_extremes([t]), t) for t in ticks]
    for arc in arcs:
        start = arc.start
        while start < arc.end:
            end = min(start + 0.25, arc.end)
            items.append(((start + end) / 2, arc_extremes(arc, start, end), (arc, start, end)))
            start = end
    items.sort(key=lambda item: item[0])
    best = None
    for first in range(len(items)):
        result, current, extremes = [], [], None
        for i in range(len(items)):
            item = items[(first + i) % len(items)]
            joined = item[1] if extremes is None else join_extremes(extremes, item[1])
            if current and distance(box(joined)) < min_distance:
                result.append(current)
                current, extremes = [item], item[1]
            else:
                current.append(item)
                extremes = joined
        result.append(current)
        if best is None or len(result) < len(best):
            best = result
    groups = []
    for group in sorted(best, key=lambda g: g[0][0]):
        group_ticks = [item[2] for item in group if isinstance(item[2], Tick)]
        pieces = []
        for arc in arcs:
            slices = [
                item[2] for item in group if not isinstance(item[2], Tick) and item[2][0] is arc
            ]
            if slices:
                start = min(s for _, s, _ in slices)
                end = max(e for _, _, e in slices)
                # the slices of a group are neighbours, one piece covers them
                if abs(sum(e - s for _, s, e in slices) - (end - start)) > 1e-6:
                    sys.exit(f"{arc.name}: slices of a group not contiguous at {start} degree")
                pieces.append((arc, start, end))
        groups.append((group_ticks, pieces))
    return groups


def cut_arc(arc, min_distance):
    """fewest pieces whose boxes keep the distance

    A shorter piece has a smaller box, so making each piece as long as possible (in steps of
    0.25 degree) gives the fewest pieces. Near 12, 3, 6 and 9 o'clock pieces can be much longer
    than near the diagonals.
    """
    pieces = []
    start = arc.start
    while start < arc.end:
        end = start
        while end < arc.end and distance(box(arc_extremes(arc, start, min(end + 0.25, arc.end)))) >= min_distance:
            end = min(end + 0.25, arc.end)
        if end == start:
            sys.exit(f"{arc.name}: no cut found at {start} degree")
        pieces.append((start, end))
        start = end
    return pieces


def hand_box(hand, angle):
    s, c = math.sin(angle), math.cos(angle)
    points = [
        (-hand.tail, -hand.half_width),
        (hand.shoulder, -hand.half_width),
        (hand.tip, 0),
        (hand.shoulder, hand.half_width),
        (-hand.tail, hand.half_width),
    ]
    xs, ys = [], []
    for along, across in points:
        along = along * INNER_RADIUS if along != 0 else 0
        xs.append(CENTER + along * s + across * c)
        ys.append(CENTER - along * c + across * s)
    return min(xs) - 1, min(ys) - 1, max(xs) + 1, max(ys) + 1


def overlap(a, b):
    return a[0] < b[2] and b[0] < a[2] and a[1] < b[3] and b[1] < a[3]


def expression(a, b):
    # without a dependency on the size the property is a constant and needs no binding
    if abs(a) < 5e-7:
        return f"{b:.4f}"
    if abs(b) < 5e-5:
        return f"size_float * {a:.6f}"
    return f"size_float * {a:.6f} {'+' if b > 0 else '-'} {abs(b):.4f}"


# Femtovg, the renderer of Slint on the desktop, gets from Slint whether an outline is solid or a
# hole: clockwise on the screen is a hole, and femtovg then draws its anti-aliased edge outside,
# 1 px fatter on each side (the software renderer of the MCUs draws both alike). Slint takes the
# direction without the closing edge, which decides it for a thin outline (a tick) either way. So
# all filled outlines run counterclockwise on the screen and end with their first point again: the
# closing edge is then part of the direction Slint calculates. Except the static ticks, the most
# outlines: each point costs about 90 bytes of heap on the RP2040, so a tick starts at a corner
# where the edge Slint leaves out doesn't change the direction (see tick_subpath).

# instrument sizes the start corner of a static tick is checked for
CHECK_SIZES = (60, 120, 240, 480, 960, 1920, 3840)


def slint_direction(points):
    """the direction as Slint calculates it (without the closing edge): > 0 counterclockwise on
    the screen (y down), a solid outline for femtovg"""
    return sum((x1 - x0) * (y1 + y0) for (x0, y0), (x1, y1) in zip(points, points[1:]))


def counterclockwise(points):
    """the points of an outline counterclockwise on the screen and closed (the first point again
    at the end), from the same first point (a triangle fan starts there, see turn_coordinator)"""
    if points[-1] == points[0]:
        points = points[:-1]
    if slint_direction(points + points[:1]) < 0:
        points = points[:1] + points[:0:-1]
    return points + points[:1]


def check_counterclockwise(points, name):
    """points of a generated outline, as they are written (closed)"""
    if points[-1] != points[0] or slint_direction(points) <= 0:
        sys.exit(f"{name}: outline not counterclockwise and closed, femtovg would draw it fatter")


def viewbox_lines(extremes):
    (ax0, bx0), (ay0, by0), (ax1, bx1), (ay1, by1) = extremes
    return [
        f"        viewbox-x: {expression(ax0, bx0 - 1)};",
        f"        viewbox-y: {expression(ay0, by0 - 1)};",
        f"        viewbox-width: {expression(ax1 - ax0, bx1 - bx0 + 2)};",
        f"        viewbox-height: {expression(ay1 - ay0, by1 - by0 + 2)};",
        "        x: self.viewbox-x * 1px;",
        "        y: self.viewbox-y * 1px;",
        "        width: self.viewbox-width * 1px;",
        "        height: self.viewbox-height * 1px;",
    ]


def path(comment, extremes, color, elements):
    out = [f"    // {comment}", "    Path {"]
    out += viewbox_lines(extremes)
    out.append(f"        fill: {color};")
    out += elements
    out.append("    }")
    out.append("")
    return out


def tick_subpath(tick, origin):
    """a static tick, counterclockwise and not closed (see counterclockwise()): from the corner
    where the direction Slint calculates without the closing edge is positive by the largest
    margin at all CHECK_SIZES, in the coordinates of the path (from `origin`, the A and B of the
    upper left corner of its box)"""
    (ax0, bx0), (ay0, by0) = origin

    def local(corner, size):
        (ax, bx), (ay, by) = tick_coefficients(tick, corner, "x"), tick_coefficients(tick, corner, "y")
        # the viewbox starts 1 unit before the box, see viewbox_lines
        return size * (ax - ax0) + bx - bx0 + 1, size * (ay - ay0) + by - by0 + 1

    check_counterclockwise(
        [local(c, SIZE) for c in TICK_CORNERS + TICK_CORNERS[:1]], f"tick at {tick.angle:g}deg"
    )
    margin, corners = max(
        (
            min(slint_direction([local(c, size) for c in turned]) / size**2 for size in CHECK_SIZES),
            turned,
        )
        for turned in (TICK_CORNERS[i:] + TICK_CORNERS[:i] for i in range(len(TICK_CORNERS)))
    )
    if margin <= 0:
        sys.exit(f"tick at {tick.angle:g}deg: no corner to start from, femtovg would draw it fatter")
    out = []
    for i, corner in enumerate(corners):
        out.append("")
        out.append(f"        {'MoveTo' if i == 0 else 'LineTo'} {{")
        out.append(f"            x: {expression(*tick_coefficients(tick, corner, 'x'))};")
        out.append(f"            y: {expression(*tick_coefficients(tick, corner, 'y'))};")
        out.append("        }")
    out.append("")
    out.append("        Close { }")
    return out


def tick_path(group, pieces=()):
    """a group of ticks, with the pieces of arcs of their colour that share its path"""
    extremes = tick_extremes(group)
    for piece in pieces:
        extremes = join_extremes(extremes, arc_extremes(*piece))
    comment = ", ".join(
        [f"{arc.name} {start:g}deg to {end:g}deg" for arc, start, end in pieces]
        + [f"{t.angle:g}deg" for t in group]
    )
    elements = [line for piece in pieces for line in arc_subpath(*piece)]
    elements += [line for tick in group for line in tick_subpath(tick, extremes[:2])]
    return path(comment, extremes, group[0].color, elements)


def card_tick_path(group, card_box):
    first, last = group[0].angle, group[-1].angle
    out = [f"    // card ticks {first:g}deg to {last:g}deg, they turn with the card", "    Path {"]
    out += viewbox_lines(card_box)
    out.append(f"        fill: {group[0].color};")
    for tick in group:
        for i, corner in enumerate(TICK_CORNERS + TICK_CORNERS[:1]):
            # offset from the center on the card before it is turned
            ax, bx = tick_coefficients(tick, corner, "x")
            ay, by = tick_coefficients(tick, corner, "y")
            px, py = expression(ax - 0.5, bx), expression(ay - 0.5, by)
            out.append("")
            out.append(f"        {'MoveTo' if i == 0 else 'LineTo'} {{")
            # written out instead of calling card_x/card_y: the compiler then reads each
            # property once per path; in a function it reads them (and computes their sine and
            # cosine) again for every call, and each read costs a dependency node of heap
            out.append(f"            x: center + ({px}) * cos_heading + ({py}) * sin_heading;")
            out.append(f"            y: center - ({px}) * sin_heading + ({py}) * cos_heading;")
            out.append("        }")
        out.append("")
        out.append("        Close { }")
    out.append("    }")
    out.append("")
    return out


def card_label(angle, text, radius):
    a = math.radians(angle)
    px = expression(ratio(radius) * math.sin(a), 0)
    py = expression(-ratio(radius) * math.cos(a), 0)
    return [
        f"    // {angle:g}deg",
        "    Text {",
        f"        x: (center + ({px}) * cos_heading + ({py}) * sin_heading - label_half_width) * 1px;",
        f"        y: (center - ({px}) * sin_heading + ({py}) * cos_heading - label_half_height) * 1px;",
        "        width: 2px * label_half_width;",
        "        height: 2px * label_half_height;",
        f'        text: "{text}";',
        "        color: Theme.marking;",
        "        font-size: large_font_size;",
        "        horizontal-alignment: TextHorizontalAlignment.center;",
        "        vertical-alignment: TextVerticalAlignment.center;",
        "    }",
        "",
    ]


def shape_points(shape):
    """(A, A) of x and y of all points of a shape"""
    return [
        (0.5 + ratio(x), 0.5 + ratio(y)) for polygon in shape.polygons for x, y in polygon
    ]


def shape_extremes(shape):
    points = shape_points(shape)
    xs = [p[0] for p in points]
    ys = [p[1] for p in points]
    return (min(xs), 0), (min(ys), 0), (max(xs), 0), (max(ys), 0)


def shape_box(shape):
    """box in px at SIZE, an outline reaches half its stroke width beyond the points"""
    x0, y0, x1, y1 = box(shape_extremes(shape))
    half = shape.stroke_px / 2
    return x0 - half, y0 - half, x1 + half, y1 + half


def shape_path(shape):
    out = [f"    // {shape.name}", "    Path {"]
    lines = viewbox_lines(shape_extremes(shape))
    if shape.stroke_width:
        # Slint fits the viewbox into the box less the stroke width, so the box is larger by
        # the stroke width: the viewbox is then drawn 1:1, and the stroke fits into the box
        lines = lines[:4] + [
            "        x: self.viewbox-x * 1px - self.stroke-width / 2;",
            "        y: self.viewbox-y * 1px - self.stroke-width / 2;",
            "        width: self.viewbox-width * 1px + self.stroke-width;",
            "        height: self.viewbox-height * 1px + self.stroke-width;",
            f"        stroke: {shape.color};",
            f"        stroke-width: {shape.stroke_width};",
            # A miter join would reach far beyond the sharp nose. Bevel joins and flat ends (the
            # default cap): zeno builds round joins and ends from arcs, which costs about 30 ms
            # per frame for the jet of the heading indicator on the RP2040, flat ones 3 ms.
            "        stroke-line-join: bevel;",
        ]
    else:
        lines.append(f"        fill: {shape.color};")
    out += lines
    for polygon in shape.polygons:
        if not shape.stroke_width:
            polygon = counterclockwise(polygon)
            check_counterclockwise(polygon, shape.name)
        for i, (x, y) in enumerate(polygon):
            out.append("")
            out.append(f"        {'MoveTo' if i == 0 else 'LineTo'} {{")
            out.append(f"            x: {expression(0.5 + ratio(x), 0)};")
            out.append(f"            y: {expression(0.5 + ratio(y), 0)};")
            out.append("        }")
        if shape.closed:
            out.append("")
            out.append("        Close { }")
    out.append("    }")
    out.append("")
    return out


def rotor_half_extents(rotor):
    """half width and half height of a symmetric box around the center that contains the
    shape before it is turned (in units of the inner radius)"""
    points = [p for polygon in rotor.polygons for p in polygon]
    return max(abs(x) for x, _ in points), max(abs(y) for _, y in points)


def rotor_box(rotor, angle):
    """box in px at SIZE of the turned shape, the same formula as in the .slint file, with
    the 1 unit margin of the viewbox"""
    w, h = (INNER_RADIUS * e for e in rotor_half_extents(rotor))
    a = math.radians(angle)
    ex = w * abs(math.cos(a)) + h * abs(math.sin(a))
    ey = w * abs(math.sin(a)) + h * abs(math.cos(a))
    return CENTER - ex - 1, CENTER - ey - 1, CENTER + ex + 1, CENTER + ey + 1


def rotor_path(rotor):
    w, h = rotor_half_extents(rotor)
    wx, hx = expression(ratio(w), 0), expression(ratio(h), 0)
    s, c = rotor.sin_name, rotor.cos_name
    # the box contains the turned box of the shape: half extents w * |cos| + h * |sin| and
    # w * |sin| + h * |cos|, cheaper than the smallest box over all points (fewer reads)
    out = [
        f"    // {rotor.name}, turned by the {s}/{c} angle, its box follows it",
        "    Path {",
        f"        viewbox-x: center - ({wx}) * abs({c}) - ({hx}) * abs({s}) - 1;",
        f"        viewbox-y: center - ({wx}) * abs({s}) - ({hx}) * abs({c}) - 1;",
        f"        viewbox-width: 2 * (({wx}) * abs({c}) + ({hx}) * abs({s})) + 2;",
        f"        viewbox-height: 2 * (({wx}) * abs({s}) + ({hx}) * abs({c})) + 2;",
        "        x: self.viewbox-x * 1px;",
        "        y: self.viewbox-y * 1px;",
        "        width: self.viewbox-width * 1px;",
        "        height: self.viewbox-height * 1px;",
        f"        fill: {rotor.color};",
    ]
    for polygon in rotor.polygons:
        polygon = counterclockwise(polygon)
        check_counterclockwise(polygon, rotor.name)
        for i, (x, y) in enumerate(polygon):
            px, py = expression(ratio(x), 0), expression(ratio(y), 0)
            # turned clockwise by the angle, written out (see the heading card)
            out.append("")
            out.append(f"        {'MoveTo' if i == 0 else 'LineTo'} {{")
            out.append(f"            x: center + ({px}) * {c} - ({py}) * {s};")
            out.append(f"            y: center + ({px}) * {s} + ({py}) * {c};")
            out.append("        }")
        out.append("")
        out.append("        Close { }")
    out.append("    }")
    out.append("")
    return out


def arc_subpath(arc, start, end):
    out = []
    # counterclockwise on the screen and closed (see counterclockwise()): outer edge back from
    # the end, inner edge clockwise, then the first point again
    steps = [
        ("MoveTo", end, arc.outer, None),
        ("ArcTo", start, arc.outer, "false"),
        ("LineTo", start, arc.inner, None),
        ("ArcTo", end, arc.inner, "true"),
        ("LineTo", end, arc.outer, None),
    ]
    middle = (start + end) / 2
    corners = [(end, arc.outer), (middle, arc.outer), (start, arc.outer), (start, arc.inner),
               (middle, arc.inner), (end, arc.inner), (end, arc.outer)]
    check_counterclockwise(
        [tuple(c * SIZE for c in arc_point(a, r)) for a, r in corners],
        f"{arc.name} {start:g}deg to {end:g}deg",
    )
    for element, angle, r, sweep in steps:
        x, y = arc_point(angle, r)
        out.append("")
        out.append(f"        {element} {{")
        out.append(f"            x: {expression(x, 0)};")
        out.append(f"            y: {expression(y, 0)};")
        if sweep:
            out.append(f"            radius-x: {expression(ratio(r), 0)};")
            out.append(f"            radius-y: {expression(ratio(r), 0)};")
            out.append(f"            sweep: {sweep};")
        out.append("        }")
    out.append("")
    out.append("        Close { }")
    return out


def arc_path(arc, start, end):
    return path(
        f"{arc.name}, {start:g}deg to {end:g}deg",
        arc_extremes(arc, start, end),
        arc.color,
        arc_subpath(arc, start, end),
    )


def generate(dial):
    """the generated lines and a report, exits if a static box can be reached by a hand"""
    min_distance = dial.min_distance * INNER_RADIUS
    # arcs of the colour of all ticks share the tick paths, see group_ticks_and_arcs
    tick_colors = {t.color for t in dial.ticks}
    shared = [a for a in dial.arcs if not dial.groups and tick_colors == {a.color}]
    if dial.groups:
        tick_groups = [(g, []) for g in dial.groups]
    elif shared:
        tick_groups = group_ticks_and_arcs(dial.ticks, shared, min_distance)
    else:
        tick_groups = [(g, []) for g in group_ticks(dial.ticks, min_distance)] if dial.ticks else []
    arc_pieces = [
        (arc, s, e) for arc in dial.arcs if arc not in shared for s, e in cut_arc(arc, min_distance)
    ]

    boxes = []
    for group, pieces in tick_groups:
        extremes = tick_extremes(group)
        for piece in pieces:
            extremes = join_extremes(extremes, arc_extremes(*piece))
        boxes.append(box(extremes))
    boxes += [box(arc_extremes(*p)) for p in arc_pieces]
    boxes += [box(tick_extremes([m])) for m in dial.marks]
    covered = []
    for hand in dial.hands:
        for step in range(3600):
            hand_b = hand_box(hand, math.radians(step / 10))
            if dial.max_overlap == 0:
                if any(overlap(hand_b, b) for b in boxes):
                    sys.exit(f"{dial.file}: a hand overlaps a static box at {step / 10} degree")
                continue
            # the area of the static boxes under the hand box
            area = sum(
                max(0, min(hand_b[2], b[2]) - max(hand_b[0], b[0]))
                * max(0, min(hand_b[3], b[3]) - max(hand_b[1], b[1]))
                for b in boxes
            )
            if area > dial.max_overlap:
                sys.exit(
                    f"{dial.file}: a hand covers {area:.0f} px of static boxes at "
                    f"{step / 10} degree, more than {dial.max_overlap:g}"
                )
            covered.append(area)

    out = []
    for piece in arc_pieces:
        out += arc_path(*piece)
    for group, pieces in tick_groups:
        out += tick_path(group, pieces)
    for mark in dial.marks:
        out += tick_path([mark])

    card_report = ""
    if dial.card:
        card = dial.card
        # the box of the whole card, it contains every tick at every heading
        outer = max(t.outer for t in card.ticks)
        half_width = max(t.half_width for t in card.ticks)
        card_box = (
            (0.5 - ratio(outer), -half_width),
            (0.5 - ratio(outer), -half_width),
            (0.5 + ratio(outer), half_width),
            (0.5 + ratio(outer), half_width),
        )
        # a path has one fill: the ticks of the most frequent colour are split into card.paths
        # paths, the few of any other colour (the cardinal ticks) get one path each colour
        colors = list(dict.fromkeys(t.color for t in card.ticks))
        colors.sort(key=lambda c: -sum(t.color == c for t in card.ticks))
        main = [t for t in card.ticks if t.color == colors[0]]
        per_path = math.ceil(len(main) / card.paths)
        for i in range(0, len(main), per_path):
            out += card_tick_path(main[i : i + per_path], card_box)
        for color in colors[1:]:
            out += card_tick_path([t for t in card.ticks if t.color == color], card_box)
        for angle, text in card.labels:
            out += card_label(angle, text, card.label_radius)
        # static shapes must stay outside the box of the turning card
        for shape in dial.shapes:
            if not shape.over_card and overlap(box(shape_extremes(shape)), box(card_box)):
                sys.exit(f"{dial.file}: {shape.name} overlaps the box of the card")
        card_report = (
            f", card: {card.paths} tick paths of {per_path} ticks"
            + f" and {len(colors) - 1} of other colours, {len(card.labels)} labels"
        )
    for shape in dial.shapes:
        out += shape_path(shape)

    rotor_report = ""
    if dial.rotors:
        statics = boxes + [shape_box(sh) for sh in dial.shapes]
        statics += [
            (CENTER + x0 * INNER_RADIUS, CENTER + y0 * INNER_RADIUS,
             CENTER + x1 * INNER_RADIUS, CENTER + y1 * INNER_RADIUS)
            for x0, y0, x1, y1 in dial.statics
        ]
        for rotor in dial.rotors:
            # femtovg fills a concave outline with a triangle fan from its first point, triangles
            # outside of it must cancel each other, which some GPUs don't do exactly: all
            # triangles of the fan turn the same way only if it stays inside
            for polygon in rotor.polygons:
                p0 = polygon[0]
                turns = [
                    (b[0] - p0[0]) * (c[1] - p0[1]) - (b[1] - p0[1]) * (c[0] - p0[0])
                    for b, c in zip(polygon[1:], polygon[2:])
                ]
                if min(turns) < -1e-12 and max(turns) > 1e-12:
                    sys.exit(
                        f"{dial.file}: {rotor.name}: the triangle fan from the first point leaves "
                        "the outline, start it at a point that sees all others"
                    )
            steps = int(rotor.max_angle * 10)
            for step in range(-steps, steps + 1):
                if any(overlap(rotor_box(rotor, step / 10), b) for b in statics):
                    sys.exit(
                        f"{dial.file}: {rotor.name} overlaps a static box at {step / 10} degree"
                    )
            out += rotor_path(rotor)
            rotor_report += f", {rotor.name}: no overlap up to +-{rotor.max_angle:g} degree"

    report = (
        f"{dial.file}: {len(arc_pieces)} arc paths, {len(tick_groups)} tick paths "
        f"{[len(g) for g, _ in tick_groups]}"
        + (
            f" ({sum(bool(p) for _, p in tick_groups)} with {', '.join(a.name for a in shared)})"
            if shared
            else ""
        )
        + f", {len(dial.marks)} marks, "
        + (
            f"hands cover at most {max(covered):.0f} px of static boxes"
            if covered
            else "no overlap with the hands"
            if dial.hands
            else "no hands to check"
        )
        + card_report
        + (f", {len(dial.shapes)} shapes" if dial.shapes else "")
        + rotor_report
    )
    return out, report


def attitude():
    # bank ticks in the ring, from the outer edge (1.25 of the inner radius) to the inner edge.
    # The moving inner disc has a fixed box, the square around it, which is redrawn every frame
    # while it moves. All but the 0 degree tick reach into it, the hand-chosen groups keep the
    # part of their boxes inside it small (5.7k pixels in all, 9.7k as one path), so there are no
    # hands to check. The 0 degree tick lies in the box of the ticks next to it.
    def tick(angle, width):
        return Tick(angle, 1.0, 1.25, width / 2, "Theme.marking")

    groups = [
        [tick(0, MARKING_WIDTH)] + [tick(a, MARKING_WIDTH / 2) for a in (-20, -10, 10, 20)],
        [tick(a, MARKING_WIDTH) for a in (-60, -30)],
        [tick(a, MARKING_WIDTH) for a in (30, 60)],
    ]
    return Dial("ui/attitude.slint", 0, [], groups=groups)


def altimeter():
    # ticks every 20 ft, long and wide ones every 100 ft
    ticks = [
        Tick(
            k * 360 / 50,
            0.85 if k % 5 == 0 else 0.92,
            1.0,
            MARKING_WIDTH / 2 if k % 5 == 0 else MARKING_WIDTH / 4,
            "Theme.marking",
        )
        for k in range(50)
    ]
    # 100 ft hand and the shorter, wider 1000 ft hand
    hands = [
        Hand(0.74, 0.66, 0.12, MARKING_WIDTH * 0.8),
        Hand(0.50, 0.42, 0.10, MARKING_WIDTH * 2),
    ]
    # Four paths, a quarter of the dial each around 12, 3, 6 and 9 o'clock. Groups whose boxes
    # no hand reaches would be 12 paths; each Path element costs heap and stack when the
    # instrument is created, and time every frame it is drawn. The boxes of the quarters lie at
    # the edge, only the tip of the 100 ft hand reaches into them near the diagonals: at most
    # 235 px of them are redrawn with the hand (73 on average, none at 44 % of the angles).
    groups = [[t for t in ticks if round(t.angle / 90) % 4 == q] for q in range(4)]
    # no bezel ring: the ticks reach almost to the edge, like `inner_radius` in
    # ui/altimeter.slint (0.49 of the size)
    return Dial(
        "ui/altimeter.slint", 0.79, hands, ticks, groups=groups, ring_ratio=0.01, max_overlap=250
    )


# airspeed scale: 0 to 40 kt on the first 30 degree, then 1.875 degree per kt
# (40 kt at 30 degree, 200 kt at 330 degree), like ui/airspeed.slint
def airspeed_angle(kt):
    return kt * 0.75 if kt < 40 else 30 + (kt - 40) * 1.875


# speed limits of a typical small trainer (Cessna 172), in kt
V_S0 = 40  # stall speed with flaps, start of the white arc
V_FE = 85  # highest speed with flaps, end of the white arc
V_S1 = 48  # stall speed clean, start of the green arc
V_NO = 129  # highest cruising speed, end of the green and start of the yellow arc
V_NE = 163  # never exceed, red line


def airspeed():
    # ticks every 5 kt from 40 to 200 kt, long and wide ones every 10 kt
    ticks = [
        Tick(
            airspeed_angle(kt),
            0.85 if kt % 10 == 0 else 0.92,
            1.0,
            MARKING_WIDTH / 2 if kt % 10 == 0 else MARKING_WIDTH / 4,
            "Theme.marking",
        )
        for kt in range(40, 201, 5)
    ]
    # the arcs lie in the ring, white inside, green and yellow outside; the numbers are on the
    # dial inside the ticks, the ring is too thin for three digits at the sides. Arcs on the dial
    # instead were cut into more pieces and cost 4.4 KB more heap, too much for the device.
    arcs = [
        Arc(airspeed_angle(V_S0), airspeed_angle(V_FE), 1.0, 1.04, "Theme.marking", "white arc"),
        Arc(airspeed_angle(V_S1), airspeed_angle(V_NO), 1.04, 1.10, "Theme.normal", "green arc"),
        Arc(airspeed_angle(V_NO), airspeed_angle(V_NE), 1.04, 1.10, "Theme.caution", "yellow arc"),
    ]
    marks = [Tick(airspeed_angle(V_NE), 0.92, 1.10, MARKING_WIDTH / 2, "Theme.limit")]
    hands = [Hand(0.74, 0.66, 0.12, MARKING_WIDTH * 0.8)]
    # no bezel ring: the arcs (out to 1.10) end just inside the edge, like `inner_radius` in
    # ui/airspeed.slint (0.45 of the size)
    return Dial("ui/airspeed.slint", 0.79, hands, ticks, arcs, marks, ring_ratio=0.05)


# vertical speed scale, like ui/vertical-speed.slint: 0 at 9 o'clock, climb clockwise, descent
# counterclockwise; 0 to 1000 fpm on 90 degree, 1000 to 2000 fpm compressed on 75 degree
def vertical_speed_angle(fpm):
    v = abs(fpm)
    a = v * 0.09 if v <= 1000 else 90 + (v - 1000) * 0.075
    return (270 + a if fpm >= 0 else 270 - a) % 360


def vertical_speed():
    # ticks every 100 fpm from -2000 to 2000 fpm, long and wide ones every 500 fpm
    ticks = [
        Tick(
            vertical_speed_angle(fpm),
            0.85 if fpm % 500 == 0 else 0.92,
            1.0,
            MARKING_WIDTH / 2 if fpm % 500 == 0 else MARKING_WIDTH / 4,
            "Theme.marking",
        )
        # in the order around the dial, so the grouping joins neighbours
        for fpm in range(-2000, 2001, 100)
    ]
    hands = [Hand(0.74, 0.66, 0.12, MARKING_WIDTH * 0.8)]
    # Four paths, a quarter of the dial each around 12, 3, 6 and 9 o'clock, like the altimeter
    # (groups whose boxes the needle never reaches would be 15 paths). The long ticks at +-500
    # fpm lie on the diagonals and pull the corners of their boxes in a little: at most 551 px
    # of them are redrawn with the needle (172 on average, none at 41 % of the angles).
    # Boundaries shifted around the dial, or 5 or 6 groups, cover more.
    groups = [[t for t in ticks if round(t.angle / 90) % 4 == q] for q in range(4)]
    # no bezel ring: the ticks reach almost to the edge, like `inner_radius` in
    # ui/vertical-speed.slint (0.49 of the size)
    return Dial(
        "ui/vertical-speed.slint", 0.79, hands, ticks, groups=groups, ring_ratio=0.01,
        max_overlap=560,
    )


# turn coordinator: a standard rate turn (3 degree per second) banks the aircraft symbol by
# 20 degree, onto the L and R marks; it stops at 6 degree per second (40 degree)
TURN_STANDARD_BANK = 20
TURN_MAX_BANK = 40


def turn_coordinator():
    w = MARKING_WIDTH / 2
    # level marks at 9 and 3 o'clock, standard rate marks 20 degree below them, the two of each
    # side in one path: its box lies at the edge, beyond the wing tips at any bank (checked
    # below). All four in one path would have a box across the middle.
    groups = [
        [Tick(a, 0.85, 1.0, w, "Theme.marking") for a in (270, 270 - TURN_STANDARD_BANK)],
        [Tick(a, 0.85, 1.0, w, "Theme.marking") for a in (90, 90 + TURN_STANDARD_BANK)],
    ]
    # aircraft seen from behind: wings, a fin on top and the elevator across it, on top of the
    # fuselage (a third of the wingspan); the round fuselage is a Rectangle in the .slint file, it
    # doesn't change when turned. The wings taper to 40 % of their thickness at the tips, the
    # elevator to 60 % (thinner, its tips would fade with anti-aliasing), both measured from the
    # center: the root point of the wings is hidden by the fuselage, which saves the two points
    # at its edge. Near the root the underside of the elevator turns down into the fuselage:
    # straight on, it would meet the round fuselage at a flat angle (16 degree) and leave a thin
    # dark wedge, which femtovg (the examples) draws as single dark pixels.
    # Fin and elevator are one outline, the fin ends at the elevator (the fuselage hides it
    # below): as two overlapping polygons, femtovg left their overlap black at some banks (Slint
    # takes the orientation of a subpath without its closing edge, a wrong one makes it a hole).
    # The outline starts at the right junction of fin and elevator, where the triangle fan of
    # femtovg (from the first point) covers only its inside: from the tip of the fin, the fan
    # reached across the notches between fin and elevator, where its triangles must cancel each
    # other, and the VideoCore IV GPU of the Raspberry Pi 3 left pixel artifacts there. It ends
    # with that point again: with the closing edge, Slint gets the orientation right, so femtovg
    # doesn't reverse the outline (which would start the fan at its last point).
    # Wings and tail are two paths: in one, a band needed more than 512 rasterizer cells at a
    # steep bank (a 16 KB block, see the host check). Their boxes are also smaller than the box
    # of both (166x9 and 57x54 px in level flight instead of 166x54), the flat box of the wings
    # stays clear of the tube.
    wings = [
        (-0.70, -0.012), (0.0, -0.03), (0.70, -0.012), (0.70, 0.012), (0.0, 0.03), (-0.70, 0.012),
    ]
    tail = [
        # elevator and the fairing under it, from the right junction with the fin
        (0.0125, -0.1147), (0.233, -0.109), (0.233, -0.091), (0.05, -0.0863), (0.0, -0.05),
        (-0.05, -0.0863), (-0.233, -0.091), (-0.233, -0.109), (-0.0125, -0.1147),
        # fin, back to the start
        (-0.0125, -0.22), (0.0125, -0.22), (0.0125, -0.1147),
    ]
    rotors = [
        Rotor(name, "Theme.marking", polygons, TURN_MAX_BANK, "sin_bank", "cos_bank")
        for name, polygons in (
            ("wings of the aircraft symbol", [wings]),
            ("tail of the aircraft symbol", [tail]),
        )
    ]
    statics = [
        # inclinometer tube with the ball, Rectangles in the .slint file
        (-0.546, 0.587, 0.546, 0.86),
        # "2 MIN" text below it
        (-0.25, 0.87, 0.25, 1.02),
    ]
    # L and R at 230 and 130 degree, 0.95 of the inner radius, boxes of 0.092 x 0.06 of the
    # size, like `label_radius` and `label_half_width`/`label_half_height` in the .slint file
    ring_ratio = 0.01
    half_w, half_h = (0.046 / (0.5 - ring_ratio), 0.03 / (0.5 - ring_ratio))
    for angle in (230, 130):
        a = math.radians(angle)
        x, y = 0.95 * math.sin(a), -0.95 * math.cos(a)
        statics.append((x - half_w, y - half_h, x + half_w, y + half_h))
    # no bezel ring: the marks reach almost to the edge, like `inner_radius` in the .slint file
    return Dial(
        "ui/turn-coordinator.slint", 0, [], groups=groups, rotors=rotors, statics=statics,
        ring_ratio=ring_ratio,
    )


def heading():
    # card ticks every 10 degree, long and wide ones every 30 degree, at the labels
    ticks = [
        Tick(
            a,
            0.85 if a % 30 == 0 else 0.92,
            1.0,
            MARKING_WIDTH / 2 if a % 30 == 0 else MARKING_WIDTH / 4,
            "Theme.cardinal" if a % 90 == 0 else "Theme.marking",
        )
        for a in range(0, 360, 10)
    ]
    names = {0: "N", 90: "E", 180: "S", 270: "W"}
    labels = [(a, names.get(a, str(a // 10))) for a in range(0, 360, 30)]
    # each card path rebuilds its elements every frame: 3 paths of 11 ticks need about 1.6 KB
    # each (the 4 cardinal ticks are in a fourth path of their own colour). Fewer paths cost
    # less: each has the whole card as box and is rasterized and blended over all of it every
    # frame, and each Path element costs heap and stack when the instrument is created. But 2
    # paths of 16 ticks raised the heap peak by 2 KB (with 72 ticks, one path of 10 KB or 4 paths
    # of 2.5 KB weren't found any more in the fragmented heap of the host check).
    card = Card(ticks, 3, labels, 0.68)

    # marks at 12 (the heading mark), 3, 6 and 9 o'clock, red like the aircraft symbol, over the
    # outer ends of the card ticks (there is no bezel ring), so they are redrawn with the turning
    # card like the aircraft symbol
    def ring_mark(angle):
        # a small triangle pointing to the center, as long as the small card ticks (every 10
        # degree): its tip at 0.92 of the inner radius, its base at the edge, 0.08 wide
        a = math.radians(angle)
        s, c = math.sin(a), math.cos(a)
        return [
            (r * s + side * c, -r * c + side * s)
            for r, side in ((0.92, 0.0), (1.0, -0.04), (1.0, 0.04))
        ]

    # outline of a jet seen from above, nose up: pointed nose, swept wings and tailplane, a
    # notch at the tail; the labels at the top and bottom have their inner edge at -0.59 / 0.59
    right = [
        (0.0, -0.570),     # nose
        (0.029, -0.446),
        (0.041, -0.341),
        (0.050, -0.266),   # wing root, leading edge
        (0.333, -0.029),   # wing tip
        (0.325, 0.041),
        (0.062, -0.059),   # wing root, trailing edge
        (0.054, 0.095),
        (0.041, 0.138),    # tailplane root, leading edge
        (0.187, 0.241),    # tailplane tip
        (0.175, 0.284),
        (0.050, 0.241),    # tailplane root, trailing edge
        (0.021, 0.262),
    ]
    right.append((0.0, 0.233))  # tail notch
    # 85 % of the size above, so it leaves more of the card free; moved down, away from the
    # label at the top, it still keeps clear of the one at the bottom
    right = [(x * 0.85, y * 0.85 + 0.10) for x, y in right]
    left = [(-x, y) for x, y in right]
    shapes = [
        # opposite marks share a path: its box is a narrow strip across the card, which is
        # redrawn with the card anyway (all four in one path would have the whole card as box)
        *(
            Shape(
                f"marks at {a}deg and {a + 180}deg, over the card",
                "Theme.marker",
                [ring_mark(a), ring_mark(a + 180)],
                over_card=True,
            )
            for a in (0, 90)
        ),
        # Four open lines, nose and wing, fuselage and tail of each side, their ends meet.
        # A stroke has an edge on both sides, so as one outline (and still as two halves) it
        # needs more rasterizer cells than the renderer reserves (512), and zeno doubles them to
        # a 16 KB block.
        *(
            Shape(
                f"aircraft symbol, {side} {part}, over the card", "Theme.vehicle", [line],
                over_card=True, stroke_width="Theme.vehicle_width * scale",
                stroke_px=VEHICLE_WIDTH, closed=False,
            )
            for side, half in (("left", left), ("right", right))
            for part, line in (("nose and wing", half[:7]), ("fuselage and tail", half[6:]))
        ),
    ]
    # no bezel ring: the card reaches almost to the edge, like the 0.49 in ui/heading.slint
    return Dial("ui/heading.slint", 0, [], card=card, shapes=shapes, ring_ratio=0.01)


def main():
    check = "--check" in sys.argv[1:]
    root = Path(__file__).resolve().parent.parent
    outdated = []
    for dial in (
        attitude(),
        altimeter(),
        airspeed(),
        heading(),
        vertical_speed(),
        turn_coordinator(),
    ):
        use_dial(dial)
        lines, report = generate(dial)
        print(report, file=sys.stderr)
        path = root / dial.file
        text = path.read_text()
        begin = text.index(BEGIN + "\n") + len(BEGIN) + 1
        end = text.index(END + "\n")
        # one level deeper than written above: inside the square of the instrument
        lines = [f"    {line}" if line else line for line in lines]
        new = text[:begin] + "\n".join(lines) + "\n" + text[end:]
        if new != text:
            if check:
                outdated.append(dial.file)
            else:
                path.write_text(new)
                print(f"{dial.file} updated", file=sys.stderr)
    if outdated:
        sys.exit(f"not up to date, run tools/dial-paths.py: {', '.join(outdated)}")


